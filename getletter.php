<?php
// Generate a PDF letter for an approved request.

require_once(__DIR__ . '/../../config.php');

require_login();

$id = required_param('id', PARAM_INT);
$action = optional_param('action', 'download', PARAM_ALPHA);
$request = $DB->get_record('local_training_letter', ['id' => $id], '*', MUST_EXIST);
$context = context_system::instance();
$isowner = (int)$request->userid === (int)$USER->id;
$iscoordinator = has_capability('local/training_letter:approve', $context);

if (!$isowner && !$iscoordinator) {
    require_capability('local/training_letter:approve', $context);
}

if ($request->status !== 'approved') {
    print_error('notapproved', 'local_training_letter');
}

require_once($CFG->libdir . '/pdflib.php');

$pdf = new \pdf();
$pdf->SetTitle(get_string('pluginname', 'local_training_letter'));
$pdf->SetMargins(22, 25, 22);
$pdf->SetAutoPageBreak(true, 25);
$pdf->AddPage();
$pdf->SetFont('freesans', '', 12);
$pdf->SetTextColor(35, 48, 64);

$html = '<div style="text-align:center;color:#174f91;">';
$html .= '<h2 style="color:#174f91;">GURU NANAK DEV ENGINEERING COLLEGE, LUDHIANA</h2>';
$html .= '<p style="color:#42566d;">Training and Placement Cell</p>';
$html .= '<hr style="color:#2f80d1;"><h3 style="color:#174f91;">TRAINING REQUEST LETTER</h3></div>';
$html .= '<p>Reference: TNP/TR/' . date('Y') . '/' . s($request->id) . '</p>';
$html .= '<p>Date: ' . s(userdate(time(), get_string('strftimedate', 'langconfig'))) . '</p>';
$html .= '<p>To,<br> The HR Manager<br>' . s($request->organization) . '<br>';
$html .= nl2br(s($request->postaladdress)) . '</p>';
$html .= '<p><strong>Subject: Request for student training</strong></p>';
$html .= '<p>Dear Sir/Madam,</p>';
$html .= '<p>This is to introduce ' . s($request->studentname) . ', Roll No. ' . s($request->rollno);
$html .= ', a Semester ' . s($request->semester) . ' student of ' . s($request->branch);
$html .= ' at Guru Nanak Dev Engineering College, Ludhiana.</p>';
$html .= '<p>The student wishes to undertake ' . s($request->trainingtype) . ' training in ';
$html .= s($request->trainingtitle) . ' for ' . s($request->duration) . ', starting on ';
$html .= s(userdate($request->startdate, get_string('strftimedate', 'langconfig'))) . '.</p>';
$html .= '<p>We request you to kindly consider the student for this training opportunity.</p>';
$html .= '<p>Thank you.</p><br><br>';
$html .= '<p>____________________________<br>Training and Placement Coordinator<br>';
$html .= 'Guru Nanak Dev Engineering College, Ludhiana</p>';
$html .= '<p style="color:#60748a;"><em>Generated by the Training Request Letter plugin after coordinator approval.</em></p>';

$pdf->writeHTML($html, true, false, true, false, '');
$filename = 'training-request-' . $request->id . '.pdf';
$outputmode = $action === 'preview' ? 'I' : 'D';
$pdf->Output($filename, $outputmode);
exit;
